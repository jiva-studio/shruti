"""Offline eval for the out-of-corpus memory-pass fallback.

Runs the REAL `corpus_fallback_node` (real Claude memory-pass, re-search
skipped — no live corpus here) and the REAL synthesizer fallback path over a
golden set of questions the lecture/book corpus does NOT cover, then:

1. Structural assertions per case — the right `fallback_kind`, a disclaimer on
   memory answers, a decline (and NO memory answer) on out-of-scope ones.
2. A CROSS-MODEL faithfulness judge — the answer is generated by Claude
   (`llm_fallback_knowledge`) but judged by a DIFFERENT family (Gemini,
   `llm_synthesis_planner`). A model grading its own output is self-preference
   bias; a different judge is the cheap, honest version of "validate truthfulness".

Run (needs an OpenRouter key; forces the bundled .md prompts):

    export OPENROUTER_API_KEY=...    # e.g. from infra/app/.env.dev
    export LANGFUSE_FORCE_FALLBACK=1
    PYTHONPATH=src python tests/evals/run_corpus_fallback_eval.py

Exits non-zero if any structural assertion fails or the judge flags a HIGH
fabrication risk. This is an eval harness, not a CI unit test (it costs LLM
calls); the deterministic behaviour is covered by tests/test_corpus_fallback_node.py.
"""

from __future__ import annotations

import asyncio
import sys
from dataclasses import dataclass, field
from typing import Any, Literal

from pydantic import BaseModel, Field

import shruti_chat.agent.graph.nodes.corpus_fallback as cf
from shruti_chat.agent.graph.nodes.synthesizer import _SYNTH_PROMPT_SECTIONS
from shruti_chat.agent.marker_expander import MarkerExpander
from shruti_chat.agent.prompts import build_prompt
from shruti_chat.agent.turn_aliases import TurnAliasMap
from shruti_chat.application.synthesizer_turn import run_synthesizer_turn
from shruti_chat.config import Settings
from shruti_chat.infra.llm_provider import build_llm_provider


# get_stream_writer only works inside a running graph.
cf.get_stream_writer = lambda: (lambda _p: None)


# Golden cases: questions the corpus does NOT really cover. `expect` is the
# fallback_kind we require; `disclaimer_terms` / `decline_terms` are loose
# language checks (per lang). NB: the 5 in-CORPUS questions are validated
# against the live retrieval pipeline (prod / local stack), not here — this
# harness has no corpus, so it only exercises the fallback branch.
CASES = [
    {"q": "Сколько лет манжари?", "lang": "ru", "expect": "memory"},
    {"q": "Сколько лет Кришне во Вриндаване?", "lang": "ru", "expect": "memory"},
    {"q": "How old is Krishna in Vrindavan?", "lang": "en", "expect": "memory"},
    {"q": "Какого цвета был любимый зонт Шрилы Прабхупады?", "lang": "ru", "expect": "memory"},
    {"q": "Как варить пельмени?", "lang": "ru", "expect": "out_of_scope"},
    {"q": "Who won the 2022 FIFA World Cup?", "lang": "en", "expect": "out_of_scope"},
]

_DISCLAIMER_RU = ("корпус", "по памяти", "не наш", "общих знани")
_DISCLAIMER_EN = ("corpus", "general knowledge", "couldn't find", "could not find")


class Judge(BaseModel):
    faithful: bool = Field(description="True if the answer is consistent with mainstream Gauḍīya Vaiṣṇava / ISKCON tradition and contains no invented facts.")
    fabrication_risk: Literal["low", "medium", "high"] = Field(description="Risk that the answer states fabricated specifics (verse numbers, dates, quotes, names).")
    note: str = Field(description="One short sentence on any problem, else 'ok'.")


@dataclass
class _Ctx:
    llm: Any
    request_id: str = "eval"
    langfuse_trace_id: str = ""
    embedder: Any = None
    chunk_repo: Any = None
    catalog_repo: Any = None
    aliases: Any = field(default_factory=TurnAliasMap)
    reranker: Any = None
    retrieval_lang_code: str | None = None


@dataclass
class _RT:
    context: _Ctx


async def _synthesize(llm, q, lang, kind, answer, confidence, disclaimer) -> str:
    repl = "out_of_scope" if kind == "out_of_scope" else "fallback"
    sections = tuple(repl if s == "grounding" else s for s in _SYNTH_PROMPT_SECTIONS)
    sys_prompt = build_prompt(sections, lang=lang,
                              lang_name=("русский" if lang == "ru" else "English"))
    expander = MarkerExpander(TurnAliasMap())
    out: list[str] = []
    # Mirror synthesizer_node: the disclaimer is painted deterministically
    # before the prose for the memory kind.
    if kind == "memory" and disclaimer:
        out.append(disclaimer.strip() + "\n\n")
    async for ev in run_synthesizer_turn(
        q, tool_results=[], llm=llm, expander=expander, system_prompt=sys_prompt,
        fallback_answer=(answer if kind == "memory" else None),
        fallback_confidence=confidence,
    ):
        if ev.type == "delta":
            out.append(ev.data["text"])
    return "".join(out)


async def main() -> int:
    settings = Settings()
    llm = build_llm_provider(settings)
    print(f"generator: {settings.llm_fallback_knowledge}   judge: {settings.llm_synthesis_planner}\n")
    failures = 0

    for c in CASES:
        q, lang, expect = c["q"], c["lang"], c["expect"]
        state = {"user_query": q, "lang": lang}
        update = await cf.corpus_fallback_node(state, _RT(_Ctx(llm=llm)))
        kind = update.get("fallback_kind", "(degraded)")
        conf = update.get("fallback_confidence")
        final = await _synthesize(llm, q, lang, kind, update.get("fallback_answer", ""),
                                  conf, update.get("fallback_disclaimer", ""))
        low = final.lower()

        ok = True
        if kind != expect:
            ok = False; reason = f"kind={kind}, expected {expect}"
        elif expect == "memory":
            terms = _DISCLAIMER_RU if lang == "ru" else _DISCLAIMER_EN
            if not any(t in low for t in terms):
                ok = False; reason = "no disclaimer in memory answer"
            else:
                reason = f"conf={conf}"
        else:  # out_of_scope
            reason = "declined"

        # Cross-model faithfulness judge (memory answers only).
        verdict = ""
        if kind == "memory" and ok:
            j = await llm.structured_output(
                [{"role": "system", "content": "You are a careful fact-checker of Gauḍīya Vaiṣṇava / ISKCON doctrine. Judge ONLY factual faithfulness, not style."},
                 {"role": "user", "content": f"Question: {q}\n\nAnswer:\n{final}"}],
                Judge, model=settings.llm_synthesis_planner, run_name="eval_judge",
            )
            verdict = f"judge: faithful={j.faithful} risk={j.fabrication_risk} — {j.note}"
            if j.fabrication_risk == "high":
                ok = False; reason = "judge: HIGH fabrication risk"

        flag = "PASS" if ok else "FAIL"
        if not ok:
            failures += 1
        print(f"[{flag}] ({lang}) {q}")
        print(f"       → {kind}  ({reason})")
        if verdict:
            print(f"       {verdict}")
        print(f"       answer: {final.strip()[:240].replace(chr(10),' ')}…\n")

    print(f"\n=== {len(CASES) - failures}/{len(CASES)} passed ===")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
